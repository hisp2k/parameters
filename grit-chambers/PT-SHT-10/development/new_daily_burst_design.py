"""Hydraulic balance for PT-SHT-10, 10 m3/day and a 200 L, 6 L/s slug."""
from pathlib import Path
import csv,math
import sys
sys.path.insert(0, str(Path('work/particledeps').resolve()))
sys.path.insert(1, str(Path('work/plotdeps').resolve()))
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

out=Path('outputs')
Qday_m3=10.;Vslug_m3=.2;Qpeak_m3s=.006
Qcontrolled_m3s=10/3600
D_m=.051
A_m2=math.pi*D_m**2/4
Vfluid_m3=.16254310539050704
t_in=Vslug_m3/Qpeak_m3s
t_out=Vslug_m3/Qcontrolled_m3s
Qavg=Qday_m3/86400
vcontrolled=Qcontrolled_m3s/A_m2
vavg=Qavg/A_m2
vpeak=Qpeak_m3s/A_m2
buffer_min=(Qpeak_m3s-Qcontrolled_m3s)*t_in

t=np.linspace(0,90,901)
qin=np.where(t<t_in,Qpeak_m3s,0.)
qout=np.where(t<t_out,Qcontrolled_m3s,0.)
buffer=np.maximum(0,np.minimum(t,t_in)*Qpeak_m3s-np.minimum(t,t_out)*Qcontrolled_m3s)
rows=[{'time_s':round(float(tt),2),'slug_inflow_L_s':round(float(qi*1000),6),
       'controlled_to_grit_L_s':round(float(qo*1000),6),'buffer_increment_L':round(float(vv*1000),6),
       'velocity_inlet_51mm_m_s':round(float(qo/A_m2),6)} for tt,qi,qo,vv in zip(t,qin,qout,buffer)]
with (out/'PT-SHT-10_баланс_одного_залпа.csv').open('w',encoding='utf-8-sig',newline='') as f:
    w=csv.DictWriter(f,fieldnames=rows[0].keys());w.writeheader();w.writerows(rows)

fig,axs=plt.subplots(2,1,figsize=(10,7),sharex=True,layout='constrained')
axs[0].plot(t,qin*1000,label='Поступление в буфер',color='#d16c32',lw=2)
axs[0].plot(t,qout*1000,label='Подача в бункер Ø51',color='#137b9f',lw=2)
axs[0].set(ylabel='Расход, л/с',title='Один залп 200 л при 6 л/с; насос запускается одновременно с залпом')
axs[0].legend();axs[0].grid(alpha=.2)
axs[1].plot(t,buffer*1000,color='#467b54',lw=2)
axs[1].axhline(buffer_min*1000,color='#467b54',ls=':',lw=1)
axs[1].annotate(f'Пиковое накопление {buffer_min*1000:.1f} л',xy=(t_in,buffer_min*1000),xytext=(43,95),arrowprops={'arrowstyle':'->'},fontsize=10)
axs[1].set(xlabel='Время от начала залпа, с',ylabel='Дополнительный объём в буфере, л',ylim=(0,130))
axs[1].grid(alpha=.2)
fig.suptitle('Сохранение скорости 1,36 м/с во входном патрубке во время подачи\nТеоретический баланс без задержки пуска, резерва, осадка и последующих залпов')
fig.savefig(out/'PT-SHT-10_залп_и_буфер.png',dpi=180)
plt.close(fig)

report=f'''# PT-SHT-10 — новый режим 10 м³/сут и залп 200 л

3 октября 2026 г. Цель пользователя: сохранить **около 1,36 м/с во входном патрубке Ø51 мм во время подачи**, при поступлении отдельными залпами с паузами. Исходная расчётная полость бункера 0,162543 м³; [привязка к CAD](PT-SHT-10_привязка_расчёта_к_модели.md).

## Пересчёт расходов

| Показатель | Значение |
|---|---:|
| Среднесуточный приток | 10 м³/сут = 0,4167 м³/ч = 0,11574 л/с |
| Разовый залп | 200 л при 6 л/с = 21,6 м³/ч в течение {t_in:.2f} с |
| Скорость Ø51 мм при равномерных 10 м³/сут | {vavg:.3f} м/с |
| Скорость Ø51 мм при прямом приёме залпа | {vpeak:.3f} м/с |
| Подача через Ø51 мм для 1,36 м/с | 10,0 м³/ч = {Qcontrolled_m3s*1000:.3f} л/с |
| Номинальное V/Q бункера при 10 м³/ч | {Vfluid_m3/Qcontrolled_m3s:.1f} с |
| Номинальное V/Q бункера при прямом залпе | {Vfluid_m3/Qpeak_m3s:.1f} с |

Средняя за 24 часа скорость при 10 м³/сут через неизменный Ø51 мм равна только **{vavg:.3f} м/с**. Непрерывно держать 1,36 м/с при таком чистом суточном расходе нельзя без внутренней рециркуляции. Реалистичная для принятой цели трактовка — держать 1,36 м/с **пока насос подаёт воду в бункер**, а между циклами насос останавливать. Общая работа при 10 м³/сут и 10 м³/ч составляет в идеале **1 час за сутки**.

## Баланс одного залпа

Предварительная схема: буфер перед бункером → управляемая подача 10 м³/ч → вход Ø51 мм. При запуске насоса **одновременно** с залпом за 33,33 с в буфер войдёт 200 л, в бункер уйдёт **92,59 л**, а в буфере накопится **{buffer_min*1000:.2f} л**. Всю порцию 200 л насос пропустит через бункер за **{t_out:.1f} с** от начала пуска, то есть ещё {t_out-t_in:.1f} с после конца залпа.

**{buffer_min*1000:.1f} л — математический минимум дополнительного рабочего объёма для одного залпа при мгновенном пуске и неизменной подаче.** Если насос запускается только после конца залпа, нужно вместить все **200 л**. К обоим числам требуется добавить недоступный остаток, осадок, свободный борт, допуск регулирования и объём для последовательных залпов; их размер зависит от графика. Для произвольного графика полезный объём буфера считают по максимуму накопленной разности `∫(Qвход−Qподача)dt` за весь расчётный период.

![Баланс одного залпа и накопление в буфере](PT-SHT-10_залп_и_буфер.png)

[Численная таблица с шагом 0,1 с](PT-SHT-10_баланс_одного_залпа.csv). Возможность сглаживать пики расхода буфером и необходимость проверить осаждение твёрдой фазы в нём соответствуют подходу [EPA к flow equalization](https://nepis.epa.gov/Exe/ZyPURL.cgi?Dockey=91013PZ0.TXT).

## Что менять в модели

1. **Бункер и вход Ø51 мм предварительно оставить**: при управляемой подаче 10 м³/ч его средняя скорость во входе равна прежней. Сохранять геометрию следует как исследовательский вариант, не как подтверждённое изделие.
2. Добавить перед бункером **отдельный приёмно-усреднительный объём** и управление насосом/регулятором расхода 10 м³/ч. Подачу 6 л/с напрямую в бункер не принимать, если требуется именно 1,36 м/с на входе.
3. Проверить накопление песка в буфере: предусмотреть его очистку или перемешивание и оценить изменение гранулометрии на входе бункера. Вместимость 0,162543 м³ самой CFD-полости не является полезным объёмом отдельного буфера.
4. Для нового режима решить воду и частицы при пуске, установленной подаче и остановке; подтвердить геометрию и сеточную сходимость. Предыдущая η(d) не верифицирована; 60% удержания песка не доказаны.

**Неизвестно:** число подряд идущих залпов, минимальные интервалы, задержка пуска, доступный напор/насос, концентрация и массовый расход песка. Без них нельзя окончательно назначить объём буфера и режим выгрузки осадка.
'''
(out/'PT-SHT-10_пересчёт_10м3сут_залп_200л.md').write_text(report,encoding='utf-8')
print('average L/s',Qavg*1000,'peak m3/h',Qpeak_m3s*3600,'pulse s',t_in,'velocities',vavg,vcontrolled,vpeak,'min buffer L',buffer_min*1000)
