def unresolved_entries(registry: list[NormativeDocument] | None = None) -> list[NormativeDocument]:
    """Записи, ещё требующие проверки (для release_gate и отчёта пользователю)."""
    reg = registry if registry is not None else DEFAULT_REGISTRY
    return [d for d in reg if not d.fully_resolved]
