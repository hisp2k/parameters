# ставку как когда-либо официальную/отменённую — это, по всей видимости,
# внутренняя информация предприятия, переданная напрямую в задании, а не
# общедоступный норматив. Поэтому она принимается как есть со слов
# пользователя (раздел 8 — пользователь как источник, не придуманное
# Claude утверждение) и никакая ставка в рублях/час НЕ используется нигде в
# core/technology.py — все временные оценки там в минутах, без перевода в
